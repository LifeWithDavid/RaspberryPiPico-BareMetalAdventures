;NOTE ALL THINGS ARE KEPT UNPACKED IN ARG, FAC AND ON THE STACK.
;
;IT IS ONLY WHEN SOMETHING IS STORED AWAY THAT IT IS PACKED TO FOUR
;BYTES. THE UNPACKED FORMAT HAS A SGN BYTE REFLECTING THE SIGN OF THE
